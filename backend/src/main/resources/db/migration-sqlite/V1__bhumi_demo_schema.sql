CREATE TABLE IF NOT EXISTS app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL UNIQUE,
    phone           VARCHAR(64),
    password_hash   VARCHAR(255) NOT NULL,
    full_name       VARCHAR(255) NOT NULL,
    role            VARCHAR(32)  NOT NULL,
    state           VARCHAR(128),
    district        VARCHAR(128),
    city            VARCHAR(128),
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    official_login  VARCHAR(255),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS government_record (
    khasra_number   VARCHAR(64) PRIMARY KEY,
    village         VARCHAR(255),
    city            VARCHAR(128) NOT NULL,
    district        VARCHAR(128) NOT NULL,
    owner_name      VARCHAR(255) NOT NULL,
    measurements    VARCHAR(255),
    owner_phone     VARCHAR(64),
    ulpin           VARCHAR(14),
    survey_number   VARCHAR(64),
    khata_number    VARCHAR(64),
    khewat_number   VARCHAR(64),
    khatauni_number VARCHAR(64),
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_government_record_ulpin ON government_record (ulpin);

CREATE TABLE IF NOT EXISTS authenticator_application (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applicant_user_id   BIGINT NOT NULL,
    full_name           VARCHAR(255) NOT NULL,
    personal_email      VARCHAR(255) NOT NULL,
    phone               VARCHAR(64),
    official_id_number  VARCHAR(128) NOT NULL,
    state               VARCHAR(128),
    district            VARCHAR(128),
    city                VARCHAR(128),
    status              VARCHAR(32) NOT NULL,
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS property_listing (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id               BIGINT NOT NULL,
    buyer_id                BIGINT,
    purpose                 VARCHAR(32) NOT NULL,
    type                    VARCHAR(32) NOT NULL,
    status                  VARCHAR(64) NOT NULL,
    title                   VARCHAR(255) NOT NULL,
    state                   VARCHAR(128),
    district                VARCHAR(128),
    city                    VARCHAR(128),
    address                 VARCHAR(4000),
    asking_price            DOUBLE PRECISION,
    measurements            VARCHAR(255),
    khasra_number           VARCHAR(64),
    ulpin                   VARCHAR(14),
    survey_number           VARCHAR(64),
    khata_number            VARCHAR(64),
    khewat_number           VARCHAR(64),
    khatauni_number         VARCHAR(64),
    registry_detail         VARCHAR(4000),
    house_number            VARCHAR(64),
    furnished               BOOLEAN,
    flat_number             VARCHAR(64),
    floor                   INTEGER,
    bedrooms                INTEGER,
    extra_notes             VARCHAR(4000),
    ai_summary              VARCHAR(4000),
    officer_remarks         VARCHAR(4000),
    certificate_id          BIGINT,
    latitude                DOUBLE PRECISION,
    longitude               DOUBLE PRECISION,
    verification_report_id  VARCHAR(64),
    verification_report_name VARCHAR(255),
    verification_report_type VARCHAR(128),
    verification_report_bytes BYTEA,
    virtual_jamabandi_id    VARCHAR(64),
    virtual_jamabandi_name  VARCHAR(255),
    virtual_jamabandi_type  VARCHAR(128),
    virtual_jamabandi_bytes BYTEA,
    purchase_requested_at   TIMESTAMP,
    sale_confirmed_at       TIMESTAMP,
    transferred_at          TIMESTAMP,
    created_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS property_paper (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id      BIGINT NOT NULL,
    file_id          VARCHAR(64) NOT NULL,
    original_name    VARCHAR(255),
    content_type     VARCHAR(128),
    bytes            BYTEA NOT NULL
);

CREATE TABLE IF NOT EXISTS property_photo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id      BIGINT NOT NULL,
    file_id          VARCHAR(64) NOT NULL,
    original_name    VARCHAR(255),
    content_type     VARCHAR(128),
    bytes            BYTEA NOT NULL,
    sort_order       INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS chat_message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id     BIGINT NOT NULL,
    sender_id       BIGINT NOT NULL,
    body            VARCHAR(4000) NOT NULL,
    blocked         BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS audit_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id        BIGINT,
    action          VARCHAR(64) NOT NULL,
    detail          VARCHAR(4000),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transfer_certificate (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id          BIGINT NOT NULL,
    certificate_number   VARCHAR(128) NOT NULL UNIQUE,
    khasra_number        VARCHAR(64),
    old_owner_name       VARCHAR(255),
    new_owner_name       VARCHAR(255),
    village              VARCHAR(255),
    city                 VARCHAR(128),
    district             VARCHAR(128),
    state                VARCHAR(128),
    measurements         VARCHAR(255),
    officer_id           BIGINT,
    officer_name         VARCHAR(255),
    issued_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    pdf_bytes            BYTEA NOT NULL
);

CREATE TABLE IF NOT EXISTS notification (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    channel         VARCHAR(32) NOT NULL,
    subject         VARCHAR(255) NOT NULL,
    body            VARCHAR(4000) NOT NULL,
    is_read         BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS state_admin (
    admin_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT NOT NULL UNIQUE,
    state_union_territory   VARCHAR(128) NOT NULL,
    email                   VARCHAR(255) NOT NULL UNIQUE,
    phone                   VARCHAR(64) NOT NULL,
    full_name               VARCHAR(255) NOT NULL,
    active                  BOOLEAN NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_property_status ON property_listing (status);
CREATE INDEX IF NOT EXISTS idx_property_city ON property_listing (city);
CREATE INDEX IF NOT EXISTS idx_notification_user ON notification (user_id);
CREATE INDEX IF NOT EXISTS idx_chat_property ON chat_message (property_id);
